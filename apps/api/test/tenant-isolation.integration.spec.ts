import { randomUUID, randomBytes } from 'node:crypto';
import { describe, it, expect } from 'vitest';
import { Pool } from '@dossiercle/adapters/postgres/runtime-pool';
import { FileSecretStore } from '@dossiercle/adapters/secrets/secret-store';
import { AuthorityJournal } from '@dossiercle/adapters/journal/authority-journal';
import { TenantRouter, type TenantRouterDependencies } from '@dossiercle/adapters/postgres/tenant-router';
import type { TenantVerificationContext } from '@dossiercle/adapters/postgres/provisioning-attempt';
import { ProvisioningService } from '../src/provisioning/provisioning.service.js';
import { createT06Fixture, t06Environment, t06Pool } from './private-t06-fixture.js';
const sleep = (ms: number) => new Promise(resolve => setTimeout(resolve, ms));
describe('actual PostgreSQL tenant capability, pool and version isolation', () => {
    it('binds verification to its held authority, rejects substitutions, bounds real sessions and drains versions/idle', async () => {
        const a = await createT06Fixture(true), b = await createT06Fixture(true), e = await t06Environment();
        const central = await t06Pool('control_migrator', 'control', 2), pool = await t06Pool('provisioner', 'control', 4);
        const ddl = await t06Pool('provisioner_ddl', 'postgres');
        const runtimeSecrets = new FileSecretStore(e.private + '/t06-runtime'), migrationSecrets = new FileSecretStore(e.private + '/t06-migration');
        const config = { pool, ddl, host: '127.0.0.1', port: e.pgPort, instanceId: randomUUID(), runtimeSecrets, migrationSecrets,
            journal: new AuthorityJournal('.local/journal/application'), allowed: async () => [a, b] };
        const createdPools: Pool[] = [];
        let savedContext: TenantVerificationContext | undefined;
        const dependencies: TenantRouterDependencies = { authorize: async () => false, withAuthority: async () => { throw new Error('HUMAN_ACCESS_CLOSED'); },
            locator: async (agencyId) => {
                const row = (await central.query(`SELECT a.state,l.* FROM control.agency a
     JOIN control.database_locator l ON l.agency_id=a.id WHERE a.id=$1`, [agencyId])).rows[0];
                return row ? { agencyId, state: row.state, databaseName: row.database_name, runtimeRole: row.runtime_role,
                    secretRef: row.secret_ref, secretVersion: row.secret_version, verificationVersion: BigInt(row.verification_version) } : null;
            },
            resolve: async (locator) => {
                const operation = (await central.query('SELECT id FROM control.provisioning_operation WHERE agency_id=$1', [locator.agencyId])).rows[0];
                const bytes = await runtimeSecrets.read({ agencyId: locator.agencyId, operationId: operation.id,
                    secretRef: locator.secretRef, version: locator.secretVersion, kind: 'runtime' });
                return { host: '127.0.0.1', port: e.pgPort, database: locator.databaseName, user: locator.runtimeRole, password: bytes.toString() };
            },
            createPool: options => { const result = new Pool(options); createdPools.push(result); return result; },
        };
        const router = new TenantRouter(dependencies);
        try {
            expect((await new ProvisioningService(config).wake(b.eventId)).disposition).toBe('closed');
            const bLocator = (await dependencies.locator(b.agencyId))!;
            const bCredential = await dependencies.resolve(bLocator);
            let releaseRevoker: Promise<void> | undefined;
            const service = new ProvisioningService({ ...config, instanceId: randomUUID(), afterVerification: async (attempt, resources) => {
                    const negative = async (work: (token: TenantVerificationContext) => Promise<unknown>, message: string) => {
                        await expect(attempt.run('AUDIT_CONFIRMED', async () => work(await attempt.verificationContext()))).rejects.toThrow(message);
                    };
                    const canary = `t06_canary_${a.agencyId.replaceAll('-', '')}`;
                    const migrationPassword = await migrationSecrets.read({ agencyId: a.agencyId, operationId: a.operationId,
                        secretRef: resources.migrationSecretRef, version: 1, kind: 'migration' });
                    const owner = new Pool({ host: '127.0.0.1', port: e.pgPort, database: resources.database, user: resources.migrationRole,
                        password: migrationPassword.toString(), max: 1 });
                    const mc = await owner.connect();
                    try {
                        await attempt.run('AUDIT_CONFIRMED', async () => {
                            await attempt.backend(mc, 'migration');
                            await mc.query(`CREATE TABLE business."${canary}"(id bigint GENERATED BY DEFAULT AS IDENTITY,value text)`);
                            const token = await attempt.verificationContext();
                            expect(await router.queryVerification(token, `INSERT INTO business."${canary}"(value) VALUES('own') RETURNING value`)).toEqual([{ value: 'own' }]);
                            await expect(router.queryVerification({ ...token }, 'SELECT 1')).rejects.toThrow('TENANT_CONTEXT_REFUSED');
                        });
                        const wrongSecret = new TenantRouter({ ...dependencies, resolve: async () => bCredential });
                        try {
                            await negative(token => wrongSecret.queryVerification(token, 'SELECT 1'), 'TENANT_SECRET_BINDING_REFUSED');
                        }
                        finally {
                            await wrongSecret.close();
                        }
                        const wrongPool = new TenantRouter({ ...dependencies, createPool: () => new Pool({ ...bCredential, max: 1 }) });
                        try {
                            await negative(token => wrongPool.queryVerification(token, 'SELECT 1'), 'TENANT_CONNECTION_SUBSTITUTED');
                        }
                        finally {
                            await wrongPool.close();
                        }
                        const wrongLocator = new TenantRouter({ ...dependencies, locator: async () => bLocator });
                        try {
                            await negative(token => wrongLocator.queryVerification(token, 'SELECT 1'), 'TENANT_VERIFICATION_CLOSED');
                        }
                        finally {
                            await wrongLocator.close();
                        }
                        for (const database of [bCredential.database, 'control', 'keycloak', 'privacyidea', 'inngest', 'postgres', 'template1']) {
                            const cross = new Pool({ host: '127.0.0.1', port: e.pgPort, database, user: resources.runtimeRole, password: resources.runtimePassword.toString(), max: 1 });
                            try {
                                await expect(cross.query('SELECT 1')).rejects.toMatchObject({ code: '42501' });
                            }
                            finally {
                                await cross.end();
                            }
                        }
                        await negative(async (token) => {
                            await mc.query('UPDATE agency_metadata SET agency_id=$1', [b.agencyId]);
                            try {
                                return await router.queryVerification(token, 'SELECT 1');
                            }
                            finally {
                                await mc.query('UPDATE agency_metadata SET agency_id=$1', [a.agencyId]);
                            }
                        }, 'AGENCY_SCHEMA_CLOSED');
                        await negative(async (token) => {
                            await mc.query(`GRANT INSERT ON agency_metadata TO "${resources.runtimeRole}"`);
                            try {
                                return await router.queryVerification(token, 'SELECT 1');
                            }
                            finally {
                                await mc.query(`REVOKE INSERT ON agency_metadata FROM "${resources.runtimeRole}"`);
                            }
                        }, 'AGENCY_RUNTIME_ACL_DIVERGED');
                        await negative(async (token) => {
                            const busy = [router.queryVerification(token, 'SELECT pg_sleep(3.2)'), router.queryVerification(token, 'SELECT pg_sleep(3.2)')];
                            await sleep(150);
                            expect((await central.query('SELECT count(*)::int AS n FROM pg_stat_activity WHERE usename=$1', [resources.runtimeRole])).rows[0].n).toBe(2);
                            const start = Date.now();
                            try {
                                await router.queryVerification(token, 'SELECT 1');
                            }
                            finally {
                                expect(Date.now() - start).toBeGreaterThanOrEqual(1800);
                                expect(Date.now() - start).toBeLessThan(3500);
                                await Promise.all(busy);
                            }
                        }, 'TENANT_CAPACITY_UNAVAILABLE');
                        const siblings = Array.from({ length: 3 }, () => new TenantRouter(dependencies));
                        const fifth = new TenantRouter(dependencies), beforePools = createdPools.length;
                        try {
                            await negative(async (token) => {
                                const busy = [router, ...siblings].map(r => r.queryVerification(token, 'SELECT pg_sleep(1.5)'));
                                await sleep(200);
                                try {
                                    expect(createdPools.length - beforePools).toBe(3);
                                    expect((await central.query('SELECT count(*)::int AS n FROM pg_stat_activity WHERE usename=$1', [resources.runtimeRole])).rows[0].n).toBeLessThanOrEqual(8);
                                    await fifth.queryVerification(token, 'SELECT 1');
                                }
                                finally {
                                    await Promise.all(busy);
                                }
                            }, 'TENANT_CAPACITY_UNAVAILABLE');
                        }
                        finally {
                            await Promise.all([...siblings, fifth].map(r => r.close()));
                        }
                        const sqlStart = Date.now();
                        await expect(attempt.run('AUDIT_CONFIRMED', async () => router.queryVerification(await attempt.verificationContext(), 'SELECT pg_sleep(7)'))).rejects.toThrow();
                        expect(Date.now() - sqlStart).toBeGreaterThanOrEqual(4700);
                        expect(Date.now() - sqlStart).toBeLessThan(6500);
                        await attempt.run('AUDIT_CONFIRMED', async () => {
                            const token = await attempt.verificationContext();
                            savedContext = token;
                            const oldPid = (await router.queryVerification<{
                                pid: number;
                            }>(token, 'SELECT pg_backend_pid() AS pid'))[0]!.pid;
                            const password2 = Buffer.from(randomBytes(32).toString('base64url'));
                            await runtimeSecrets.publish({ agencyId: a.agencyId, operationId: a.operationId, secretRef: resources.secretRef, version: 2, kind: 'runtime' }, password2);
                            await ddl.query(`ALTER ROLE "${resources.runtimeRole}" PASSWORD '${password2.toString()}'`);
                            await central.query('UPDATE control.database_locator SET secret_version=2,verification_version=2 WHERE agency_id=$1', [a.agencyId]);
                            const pid2 = (await router.queryVerification<{
                                pid: number;
                            }>(token, 'SELECT pg_backend_pid() AS pid'))[0]!.pid;
                            expect(pid2).not.toBe(oldPid);
                            expect((await central.query('SELECT count(*)::int AS n FROM pg_stat_activity WHERE pid=$1', [oldPid])).rows[0].n).toBe(0);
                            expect((await runtimeSecrets.read({ agencyId: a.agencyId, operationId: a.operationId, secretRef: resources.secretRef, version: 1, kind: 'runtime' })).equals(resources.runtimePassword)).toBe(true);
                            expect((await runtimeSecrets.read({ agencyId: a.agencyId, operationId: a.operationId, secretRef: resources.secretRef, version: 2, kind: 'runtime' })).equals(password2)).toBe(true);
                            const poolCount = createdPools.length;
                            await sleep(61500);
                            expect((await central.query('SELECT count(*)::int AS n FROM pg_stat_activity WHERE usename=$1', [resources.runtimeRole])).rows[0].n).toBe(0);
                            await router.queryVerification(token, 'SELECT 1');
                            expect(createdPools.length).toBe(poolCount + 1);
                            expect((await central.query('SELECT count(*)::int AS n FROM pg_stat_activity')).rows[0].n).toBeLessThanOrEqual(80);
                            expect((await central.query("SELECT current_setting('max_connections')::int AS n")).rows[0].n).toBe(100);
                            const revoker = await central.connect();
                            await revoker.query('BEGIN');
                            await revoker.query("SET application_name='t06-test-authority-writer'");
                            let completed = false;
                            releaseRevoker = revoker.query('UPDATE identity.account_authority SET status=status WHERE subject_id=$1', [a.subjectId])
                                .then(async () => { completed = true; await revoker.query('ROLLBACK'); revoker.release(); });
                            await sleep(100);
                            expect(completed).toBe(false);
                            expect((await central.query("SELECT count(*)::int AS n FROM pg_stat_activity WHERE application_name='t06-test-authority-writer' AND wait_event_type='Lock'")).rows[0].n).toBe(1);
                            await router.queryVerification(token, `SELECT value FROM business."${canary}"`);
                            expect(completed).toBe(false);
                            await mc.query(`DROP TABLE business."${canary}"`);
                        });
                    }
                    finally {
                        mc.release();
                        await owner.end();
                    }
                } });
            expect((await service.wake(a.eventId)).disposition).toBe('closed');
            await releaseRevoker;
            expect(savedContext).toBeTruthy();
            await expect(router.queryVerification(savedContext!, 'SELECT 1')).rejects.toThrow();
            await expect(router.context({ subjectId: a.subjectId, agencyId: a.agencyId, sessionEpoch: 1n })).rejects.toThrow('TENANT_AUTHORIZATION_CLOSED');
            const row = (await central.query('SELECT state,activated_at FROM control.agency WHERE id=$1', [a.agencyId])).rows[0];
            expect(row).toEqual({ state: 'READY', activated_at: null });
        }
        finally {
            await router.close();
            await pool.end();
            await ddl.end();
            await central.end();
        }
    }, 150000);
});
